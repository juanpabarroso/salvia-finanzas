'use strict';
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const BASE=process.env.SALVIA_TEST_URL||'http://127.0.0.1:8765';
async function enterWorkspace(page){if(await page.locator('body.s-welcome').count())await page.locator('[data-welcome-go="dashboard"]').click()}
async function navigate(page,id){const link=page.locator('#nav [data-route="'+id+'"]');await link.waitFor({state:'attached'});if(!await link.isVisible()){const group=link.locator('xpath=ancestor::div[contains(@class,"s-group")]');if(await group.count()){const toggle=group.locator('.s-group-toggle');if(await toggle.isVisible())await toggle.click()}}if(!await link.isVisible())throw Error('Navigation link hidden after expanding group: '+id);await link.click()}
const wait=ms=>new Promise(r=>setTimeout(r,ms));
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(BASE,{waitUntil:'domcontentloaded'});
  await page.locator('[data-route="movements"]').waitFor({state:'attached'});
  await page.waitForFunction(()=>Boolean(window.salviaStore?.get&&window.SalviaFinance?.forecastMonth));
  await page.evaluate(()=>{
    const now=new Date(),month=now.getFullYear()+'-'+String(now.getMonth()+1).padStart(2,'0'),date=month+'-05';
    const d=window.salviaStore.get();
    d.accounts=[{id:'bank',name:'Cuenta prueba',kind:'bank',opening:3000},{id:'saving',name:'Remunerada',kind:'savings',opening:500}];
    d.tx=[{id:'salary',type:'income',date,concept:'Nómina',amount:1500,to:'bank'},{id:'rent',type:'expense',date,concept:'Alquiler',amount:400,from:'bank',category:'Vivienda'}];
    d.recurring=[];d.debts=[];d.salviaSuppressedExpenseOccurrences=[];d.salviaSuppressedDebtOccurrences=[];
    window.salviaStore.replace(d);
  });
  await page.reload({waitUntil:'domcontentloaded'});
  await enterWorkspace(page);
  await navigate(page,'movements');
  await page.waitForSelector('#sg-add');
  const saved=await page.evaluate(()=>window.salviaStore.get());
  assert.equal(saved.tx.length,2,'movements survive reload');
  assert.equal(saved.accounts.find(a=>a.id==='saving').kind,'savings');
  await page.locator('[data-sg-edit="rent"]').click();
  await page.locator('#sg-form [name="amount"]').fill('350');
  await page.locator('#sg-form button[type="submit"]').click();
  assert.equal(await page.evaluate(()=>window.salviaStore.get().tx.find(t=>t.id==='rent').amount),350,'expense correction persisted');
  await page.reload({waitUntil:'domcontentloaded'});
  await enterWorkspace(page);
  assert.equal(await page.evaluate(()=>window.salviaStore.get().tx.find(t=>t.id==='rent').amount),350,'correction survives reload');
  await navigate(page,'movements');
  await page.locator('[data-sg-edit="rent"]').click();
  page.once('dialog',dialog=>dialog.accept());
  await page.locator('#sg-delete').click();
  assert.equal(await page.evaluate(()=>window.salviaStore.get().tx.some(t=>t.id==='rent')),false,'expense removed after cancellation');
  await page.reload({waitUntil:'domcontentloaded'});
  await enterWorkspace(page);
  assert.equal(await page.evaluate(()=>window.salviaStore.get().tx.some(t=>t.id==='rent')),false,'cancellation survives reload');
  await navigate(page,'accounts');
  const frame=page.frameLocator('#salvia-v041-frame');
  await frame.locator('body').waitFor();
  await page.waitForFunction(()=>{const w=document.getElementById('salvia-v041-frame')?.contentWindow;return Boolean(w?.document?.body?.textContent?.includes('Patrimonio'))},null,{timeout:12000});
  const bridgeState=await page.evaluate(()=>({main:window.salviaStore.get(),iframeLoaded:!!document.getElementById('salvia-v041-frame').contentWindow.document.querySelector('body')}));
  assert.equal(bridgeState.main.accounts.find(a=>a.id==='saving').kind,'savings','remunerated account survives bridge');
  assert.equal(bridgeState.main.tx.some(t=>t.id==='rent'),false,'cancelled expense remains absent from main ledger');
  assert(bridgeState.iframeLoaded,'patrimonio frame loaded');
  await navigate(page,'planning');
  await page.locator('[data-plan-open="calendar"]').click();
  assert.equal(await page.locator('#calendar').evaluate(el=>el.classList.contains('active')),true,'calendar route');
  const calendarCheck=await page.evaluate(()=>{const m=new Date(),period=m.getFullYear()+'-'+String(m.getMonth()+1).padStart(2,'0');document.getElementById('calMonth').value=period;document.getElementById('calMonth').dispatchEvent(new Event('change',{bubbles:true}));return {expected:window.SalviaFinance.forecastMonth(window.salviaStore.get(),m.getFullYear(),m.getMonth()+1),display:document.getElementById('calStats').textContent}});
  assert.equal(calendarCheck.expected.realExpense,0,'cancelled rent excluded from forecast');
  assert.equal(calendarCheck.expected.realIncome,1500,'salary appears exactly once');
  assert(calendarCheck.display.includes('1.500'),'calendar displays registered income');
  await page.locator('[data-route="planning"]').click();
  await page.locator('[data-plan-open="planning-detail"]').click();
  assert.equal(await page.locator('#planning').evaluate(el=>el.classList.contains('active')),true,'financial plan route');
  assert.equal(errors.length,0,'uncaught page errors: '+errors.join('; '));
  console.log('PASS desktop browser: navigation, real expense correction, cancellation, reload persistence, patrimonio frame');
  await page.close();
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  await mobile.goto(BASE,{waitUntil:'domcontentloaded'});
  await enterWorkspace(mobile);
  await mobile.locator('.s-mobile').click();
  await navigate(mobile,'planning');
  assert.equal(await mobile.locator('#planning-hub').evaluate(el=>el.classList.contains('active')),true,'mobile planning route');
  console.log('PASS mobile browser: menu and planning navigation');
  await mobile.close();
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
